// functions/src/scheduler.ts

import { onSchedule } from "firebase-functions/v2/scheduler";
import * as admin from "firebase-admin";
import { COL } from "./collections";
import { aggregateRankingThrottled } from "./ranking";
import { PhaseSchedule, SystemSettingsData } from "./types";

const db = admin.firestore();

export const scheduleHeartbeats = onSchedule({
  schedule: "every 1 minutes",
  region: "asia-northeast1",
  timeoutSeconds: 60,
}, async () => {
  const settingsRef = db.collection(COL.settings).doc("system");
  const initialSnap = await settingsRef.get();
  const currentSettings = (initialSnap.data() as SystemSettingsData | undefined) || { globalPhase: "STOP", schedules: [] };
  const now = admin.firestore.Timestamp.now();
  const nowMillis = now.toMillis();

  let phaseUpdated = false;
  const remainingSchedules: PhaseSchedule[] = [];
  const pastSchedules: PhaseSchedule[] = [];

  (currentSettings.schedules || []).forEach((sch) => {
    if (sch.time.toMillis() <= nowMillis) {
      pastSchedules.push(sch);
    } else {
      remainingSchedules.push(sch);
    }
  });

  if (pastSchedules.length > 0) {
    pastSchedules.sort((a, b) => a.time.toMillis() - b.time.toMillis());
    const latestSchedule = pastSchedules[pastSchedules.length - 1];
    currentSettings.globalPhase = latestSchedule.targetPhase;
    phaseUpdated = true;
  }

  // オートパイロット
  if (currentSettings.loopEnabled && currentSettings.loopIntervalMinutes && Array.isArray(currentSettings.loopScenario)) {
    const upcomingEventsSnap = await db.collection(COL.events)
      .where("isProcessed", "==", false)
      .where("time", ">", now)
      .orderBy("time", "asc")
      .limit(1)
      .get();

    if (upcomingEventsSnap.empty) {
      const batch = db.batch();
      const cycleStartTime = new Date(nowMillis + 60 * 1000).getTime();

      currentSettings.loopScenario.forEach((scenario) => {
        const eventTime = new Date(cycleStartTime + (scenario.offsetSeconds || 0) * 1000);
        batch.set(db.collection(COL.events).doc(), {
          time: admin.firestore.Timestamp.fromDate(eventTime),
          publicNewsPresetId: scenario.publicNewsPresetId || null,
          postNewsPresetId: scenario.postNewsPresetId || null,
          postNewsDelaySeconds: scenario.postNewsDelaySeconds ?? null,
          insiderNewsPresetId: scenario.insiderNewsPresetId || null,
          priceChanges: scenario.priceChanges || null,
          signageTargetId: scenario.signageTargetId || scenario.signageAction?.signageId || null,
          breakingVideoId: scenario.breakingVideoId || null,
          signageAction: scenario.signageAction || null,
          isProcessed: false,
          isAutoGenerated: true
        });
      });
      await batch.commit();
    }
  }

  if (phaseUpdated) {
    await settingsRef.update({
      globalPhase: currentSettings.globalPhase,
      schedules: remainingSchedules
    });
  }

  await aggregateRankingThrottled();
  // Stock ticks are invoked by docker/scripts/local-runner.cjs. Cloud Tasks is
  // deliberately not part of this local-only distribution.
});
