import { PlayCircle, RotateCcw } from "lucide-react";
import Button from "../../ui/Button";
import { Card, CardContent, CardHeader, CardTitle } from "../../ui/Card";
import { useScenarioOperations } from "../../../hooks/useScenarioOperations";
import type { ScenarioEvent } from "../../../types/scenario";

interface Props {
  events: ScenarioEvent[];
  sessionName?: string;
  onResetComplete?: () => void;
}

export default function GameOpsPanel({ events, sessionName, onResetComplete }: Props) {
  const { startGameNow, resetAllToPending } = useScenarioOperations();
  const unprocessedCount = events.filter(event => !event.isProcessed && event.isAutoGenerated !== true).length;

  const handleReset = async () => {
    const completed = await resetAllToPending(events);
    if (completed) onResetComplete?.();
  };

  return (
    <Card>
      <CardHeader className="p-4">
        <CardTitle className="flex items-center gap-2 text-base"><PlayCircle size={18} /> ゲーム操作</CardTitle>
        {sessionName && <p className="text-xs font-bold text-on-surface-variant">対象シナリオ: {sessionName}</p>}
      </CardHeader>
      <CardContent className="grid gap-2 p-4">
        <Button className="h-12 w-full px-3 text-sm" disabled={unprocessedCount === 0} onClick={() => startGameNow(events)}>
          <PlayCircle size={16} className="shrink-0" /> 即座開戦
        </Button>
        <Button className="h-12 w-full px-3 text-sm" variant="outline" disabled={events.length === 0} onClick={handleReset}>
          <RotateCcw size={16} className="shrink-0" /> 全イベントリセット
        </Button>
      </CardContent>
    </Card>
  );
}
