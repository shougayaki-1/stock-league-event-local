import {
  collection,
  doc,
  addDoc,
  updateDoc,
  deleteDoc,
  onSnapshot,
  query,
  orderBy,
  limit,
  writeBatch,
  Timestamp,
  type DocumentReference,
  type DocumentData,
  type QuerySnapshot,
  type Unsubscribe,
  type WriteBatch,
} from "firebase/firestore";
import { db } from "../lib/firebase";
import type { ScenarioEvent } from "../types/scenario";
import type { PriceChangeTarget } from "../types/domain";

export const EVENTS_COLLECTION = "events";

const getSafeOffsetSeconds = (event: Pick<ScenarioEvent, "offsetSeconds">) => (
  typeof event.offsetSeconds === "number" && !Number.isNaN(event.offsetSeconds) ? event.offsetSeconds : 0
);

function toScenarioEvent(id: string, data: DocumentData): ScenarioEvent {
  return {
    id,
    time: data.time ?? null,
    offsetSeconds: typeof data.offsetSeconds === "number" ? data.offsetSeconds : 0,
    priceChanges: data.priceChanges ?? null,
    publicNewsPresetId: data.publicNewsPresetId ?? null,
    postNewsPresetId: data.postNewsPresetId ?? null,
    postNewsDelaySeconds: data.postNewsDelaySeconds ?? null,
    insiderNewsPresetId: data.insiderNewsPresetId ?? null,
    breakingVideoId: data.breakingVideoId ?? null,
    signageAction: data.signageAction ?? null,
    signageTargetId: data.signageTargetId ?? data.signageAction?.signageId ?? null,
    sessionId: data.sessionId ?? null,
    selectedBranches: data.selectedBranches ?? null,
    processedParts: data.processedParts ?? null,
    isProcessed: data.isProcessed === true,
    isAutoGenerated: data.isAutoGenerated === true ? true : undefined,
  };
}

export function subscribeUpcomingEvents(
  onNext: (events: ScenarioEvent[]) => void,
  maxCount = 300
): Unsubscribe {
  const q = query(collection(db, EVENTS_COLLECTION), orderBy("time", "asc"), limit(maxCount));
  return onSnapshot(q, (snap: QuerySnapshot) => {
    onNext(snap.docs.map(d => toScenarioEvent(d.id, d.data())));
  });
}

export interface EventWritePayload {
  time: Timestamp | null;
  offsetSeconds: number;
  priceChanges: PriceChangeTarget[] | null;
  publicNewsPresetId: string | null;
  postNewsPresetId: string | null;
  postNewsDelaySeconds: number | null;
  insiderNewsPresetId: string | null;
  signageTargetId: string | null;
  sessionId: string | null;
  selectedBranches?: null;
  processedParts?: null;
  isProcessed: boolean;
}

const clonePlainValue = <T>(value: T | null | undefined): T | null => (
  value == null ? null : JSON.parse(JSON.stringify(value)) as T
);

export function buildCopiedEventPayload(source: ScenarioEvent, targetSessionId: string | null): EventWritePayload {
  return {
    time: null,
    offsetSeconds: getSafeOffsetSeconds(source),
    priceChanges: clonePlainValue(source.priceChanges),
    publicNewsPresetId: source.publicNewsPresetId ?? null,
    postNewsPresetId: source.postNewsPresetId ?? null,
    postNewsDelaySeconds: source.postNewsDelaySeconds ?? null,
    insiderNewsPresetId: source.insiderNewsPresetId ?? null,
    signageTargetId: source.signageTargetId ?? source.signageAction?.signageId ?? null,
    sessionId: targetSessionId,
    processedParts: null,
    selectedBranches: null,
    isProcessed: false,
  };
}

export async function createEvent(payload: EventWritePayload): Promise<DocumentReference> {
  return addDoc(collection(db, EVENTS_COLLECTION), payload);
}

export async function updateEvent(
  eventId: string,
  payload: Partial<EventWritePayload>
): Promise<void> {
  await updateDoc(doc(db, EVENTS_COLLECTION, eventId), payload);
}

export async function deleteEvent(eventId: string): Promise<void> {
  await deleteDoc(doc(db, EVENTS_COLLECTION, eventId));
}

export async function updateEventOffset(eventId: string, nextOffsetSeconds: number): Promise<void> {
  await updateDoc(doc(db, EVENTS_COLLECTION, eventId), {
    offsetSeconds: Math.max(0, nextOffsetSeconds),
    time: null,
    isProcessed: false,
    processedParts: null,
    selectedBranches: null,
  });
}

export function newEventRef(): DocumentReference {
  return doc(collection(db, EVENTS_COLLECTION));
}

export function batchDeleteEvent(batch: WriteBatch, eventId: string): void {
  batch.delete(doc(db, EVENTS_COLLECTION, eventId));
}

export function batchSetEvent(batch: WriteBatch, ref: DocumentReference, data: DocumentData): void {
  batch.set(ref, data);
}

export function batchUpdateEvent(batch: WriteBatch, eventId: string, data: Record<string, unknown>): void {
  batch.update(doc(db, EVENTS_COLLECTION, eventId), data);
}

/**
 * Shared offset->absolute-time remap used by both "start now" and "start scheduled".
 * `events` must already be pre-filtered by the caller to the desired scope
 * (e.g. unstarted-only vs. all) — this function only splits by isAutoGenerated.
 */
export function applyAbsoluteEventTimes(
  batch: WriteBatch,
  events: ScenarioEvent[],
  baseMillis: number,
  startPinEventId: string
): void {
  const autoEvents = events.filter(ev => ev.isAutoGenerated === true);
  autoEvents.forEach(ev => batchDeleteEvent(batch, ev.id));

  const manualEvents = events.filter(ev => ev.isAutoGenerated !== true);

  let baseOffset = 0;
  if (startPinEventId) {
    const pinEvent = manualEvents.find(ev => ev.id === startPinEventId);
    if (pinEvent) baseOffset = getSafeOffsetSeconds(pinEvent);
  }

  manualEvents.forEach(ev => {
    const offsetSec = getSafeOffsetSeconds(ev);
    if (offsetSec < baseOffset) {
      batchUpdateEvent(batch, ev.id, {
        time: Timestamp.fromDate(new Date(baseMillis - 1000)),
        isProcessed: true,
      });
    } else {
      const actualOffset = offsetSec - baseOffset;
      batchUpdateEvent(batch, ev.id, {
        time: Timestamp.fromDate(new Date(baseMillis + actualOffset * 1000)),
        isProcessed: false,
        processedParts: null,
        selectedBranches: null,
      });
    }
  });
}

const CHUNK_SIZE = 500;

export async function commitInChunks(operations: Array<(batch: WriteBatch) => void>): Promise<void> {
  for (let i = 0; i < operations.length; i += CHUNK_SIZE) {
    const batch = writeBatch(db);
    operations.slice(i, i + CHUNK_SIZE).forEach(op => op(batch));
    await batch.commit();
  }
}

export async function deleteEventsInChunks(eventIds: string[]): Promise<void> {
  await commitInChunks(eventIds.map(id => (batch: WriteBatch) => batchDeleteEvent(batch, id)));
}

export async function moveEventsToSessionInChunks(eventIds: string[], sessionId: string | null): Promise<void> {
  await commitInChunks(eventIds.map(eventId => (batch: WriteBatch) => batchUpdateEvent(batch, eventId, { sessionId })));
}

export async function setEventsInChunks(
  eventsToSet: Array<{ ref: DocumentReference; data: DocumentData }>
): Promise<void> {
  await commitInChunks(eventsToSet.map(item => (batch: WriteBatch) => batchSetEvent(batch, item.ref, item.data)));
}

export async function resetEventToPending(eventId: string): Promise<void> {
  const batch = writeBatch(db);
  batchUpdateEvent(batch, eventId, { isProcessed: false, time: null, processedParts: null, selectedBranches: null });
  await batch.commit();
}
