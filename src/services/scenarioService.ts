import {
  arrayUnion,
  collection,
  doc,
  addDoc,
  updateDoc,
  onSnapshot,
  query,
  orderBy,
  writeBatch,
  Timestamp,
  type Unsubscribe,
} from "firebase/firestore";
import { db } from "../lib/firebase";
import { FIRESTORE_COLLECTIONS, FIRESTORE_DOCS } from "../lib/firestorePaths";
import { VIDEO_LIBRARY_COLLECTION, type VideoLibraryItem } from "../types/videoLibrary";
import { SCHEDULE_SESSIONS_COLLECTION, type ScheduleSession } from "../types/schedule";
import type { ScenarioEvent } from "../types/scenario";
import { applyAbsoluteEventTimes, batchDeleteEvent, batchUpdateEvent } from "./eventService";

export interface PublicSignageSummary {
  id: string;
  name: string;
  location?: string;
}

export interface LoopSettings {
  loopEnabled: boolean;
  loopInterval: number;
  loopRepeatDelayMinutes: number;
}

export function subscribeScenarioVideoLibrary(onNext: (items: VideoLibraryItem[]) => void): Unsubscribe {
  return onSnapshot(collection(db, VIDEO_LIBRARY_COLLECTION), (snap) => {
    onNext(snap.docs.map(d => ({ id: d.id, ...d.data() } as VideoLibraryItem)));
  });
}

export function subscribePublicSignages(onNext: (items: PublicSignageSummary[]) => void): Unsubscribe {
  return onSnapshot(collection(db, FIRESTORE_COLLECTIONS.publicSignages), (snap) => {
    onNext(snap.docs.map(d => {
      const data = d.data();
      return { id: d.id, name: data.name || d.id, location: data.location || "" };
    }));
  });
}

export function subscribeScheduleSessions(onNext: (items: ScheduleSession[]) => void): Unsubscribe {
  const sessionsQuery = query(collection(db, SCHEDULE_SESSIONS_COLLECTION), orderBy("order", "asc"));
  return onSnapshot(sessionsQuery, (snap) => {
    onNext(snap.docs.map(d => ({ id: d.id, ...d.data() } as ScheduleSession)));
  });
}

export function subscribeLoopSettings(onNext: (settings: LoopSettings) => void): Unsubscribe {
  return onSnapshot(doc(db, ...FIRESTORE_DOCS.systemSettings), (snap) => {
    if (!snap.exists()) return;
    const data = snap.data();
    onNext({
      loopEnabled: data.loopEnabled || false,
      loopInterval: data.loopIntervalMinutes || 5,
      loopRepeatDelayMinutes: data.loopRepeatDelayMinutes || 3,
    });
  });
}

export async function enableAutoPilotFromEvents(
  events: ScenarioEvent[],
  loopInterval: number,
  loopRepeatDelayMinutes: number
) {
  const loopScenario = events
    .filter(ev => ev.isAutoGenerated !== true)
    .map(ev => ({
      offsetSeconds: ev.offsetSeconds || 0,
      publicNewsPresetId: ev.publicNewsPresetId || null,
      postNewsPresetId: ev.postNewsPresetId || null,
      postNewsDelaySeconds: ev.postNewsDelaySeconds ?? null,
      insiderNewsPresetId: ev.insiderNewsPresetId || null,
      priceChanges: ev.priceChanges || null,
      signageTargetId: ev.signageTargetId || ev.signageAction?.signageId || null,
    }));

  await updateDoc(doc(db, ...FIRESTORE_DOCS.systemSettings), {
    loopEnabled: true,
    loopIntervalMinutes: loopInterval,
    loopRepeatDelayMinutes,
    loopScenario,
  });
}

export function disableAutoPilot() {
  return updateDoc(doc(db, ...FIRESTORE_DOCS.systemSettings), { loopEnabled: false });
}

export function updateLoopIntervalMinutes(loopInterval: number) {
  return updateDoc(doc(db, ...FIRESTORE_DOCS.systemSettings), { loopIntervalMinutes: loopInterval });
}

export function updateLoopRepeatDelayMinutes(loopRepeatDelayMinutes: number) {
  return updateDoc(doc(db, ...FIRESTORE_DOCS.systemSettings), { loopRepeatDelayMinutes });
}

export async function scheduleScenarioStart(
  events: ScenarioEvent[],
  startDateTime: Date,
  startPinEventId: string
) {
  const batch = writeBatch(db);
  const unstartedEvents = events.filter(ev => !ev.isProcessed);
  const autoEvents = events.filter(ev => ev.isAutoGenerated === true);
  autoEvents.forEach(ev => batchDeleteEvent(batch, ev.id));
  applyAbsoluteEventTimes(batch, unstartedEvents, startDateTime.getTime(), startPinEventId);
  batch.update(doc(db, ...FIRESTORE_DOCS.systemSettings), {
    schedules: arrayUnion({
      time: Timestamp.fromDate(startDateTime),
      targetPhase: "RUNNING",
    }),
  });
  await batch.commit();
}

export function setMarketPhase(globalPhase: "STOP" | "RUNNING" | "EMERGENCY") {
  return updateDoc(doc(db, ...FIRESTORE_DOCS.systemSettings), { globalPhase });
}

export async function createScheduleSession(
  input: { name: string; startAt: Date; endAt: Date },
  order: number
) {
  return addDoc(collection(db, SCHEDULE_SESSIONS_COLLECTION), {
    name: input.name,
    startAt: Timestamp.fromDate(input.startAt),
    endAt: Timestamp.fromDate(input.endAt),
    order,
  });
}

export function updateScheduleSession(id: string, input: { name: string; startAt: Date; endAt: Date }) {
  return updateDoc(doc(db, SCHEDULE_SESSIONS_COLLECTION, id), {
    name: input.name,
    startAt: Timestamp.fromDate(input.startAt),
    endAt: Timestamp.fromDate(input.endAt),
  });
}

export async function deleteScheduleSession(id: string, events: ScenarioEvent[]) {
  const batch = writeBatch(db);
  events.filter(event => event.sessionId === id).forEach(event => {
    batchUpdateEvent(batch, event.id, { sessionId: null });
  });
  batch.delete(doc(db, SCHEDULE_SESSIONS_COLLECTION, id));
  await batch.commit();
}

export function makeUnscheduledSession(id: string, now = new Date()): ScheduleSession {
  const start = new Date(now);
  start.setHours(0, 0, 0, 0);
  const end = new Date(start.getTime() + 24 * 60 * 60 * 1000);
  return {
    id,
    name: "未分類",
    startAt: Timestamp.fromDate(start),
    endAt: Timestamp.fromDate(end),
    order: -1,
  };
}
