import { describe, expect, it } from "vitest";
import { buildCopiedEventPayload } from "./eventService";
import type { ScenarioEvent } from "../types/scenario";

const sourceEvent: ScenarioEvent = {
  id: "event-1",
  time: null,
  offsetSeconds: 420,
  priceChanges: [
    {
      stockId: "stock-1",
      branches: [
        {
          label: "good",
          probability: 70,
          changePercent: 12,
          deadlineMinutes: 4,
          postNewsPresetId: "branch-news",
          postNewsDelaySeconds: 30,
        },
      ],
    },
  ],
  publicNewsPresetId: "public-news",
  postNewsPresetId: "post-news",
  postNewsDelaySeconds: 15,
  insiderNewsPresetId: "insider-news",
  breakingVideoId: "video-1",
  signageTargetId: "signage-1",
  signageAction: {
    signageId: "signage-1",
    mode: "FULL_MOVIE",
    duration: 45,
    videoAssetId: "video-2",
    kind: "NORMAL",
  },
  sessionId: "source-session",
  selectedBranches: [{ stockId: "stock-1", priceChangeIndex: 0, branchIndex: 0, branchLabel: "good" }],
  processedParts: { main: true, postNews: true },
  isProcessed: true,
  isAutoGenerated: true,
};

describe("buildCopiedEventPayload", () => {
  it("keeps scenario content and writes the target session", () => {
    const payload = buildCopiedEventPayload(sourceEvent, "target-session");

    expect(payload.offsetSeconds).toBe(420);
    expect(payload.priceChanges).toEqual(sourceEvent.priceChanges);
    expect(payload.publicNewsPresetId).toBe("public-news");
    expect(payload.postNewsPresetId).toBe("post-news");
    expect(payload.postNewsDelaySeconds).toBe(15);
    expect(payload.insiderNewsPresetId).toBe("insider-news");
    expect(payload.signageTargetId).toBe("signage-1");
    expect("breakingVideoId" in payload).toBe(false);
    expect("signageAction" in payload).toBe(false);
    expect(payload.sessionId).toBe("target-session");
  });

  it("resets runtime state for a new manual reservation", () => {
    const payload = buildCopiedEventPayload(sourceEvent, null);

    expect(payload.time).toBeNull();
    expect(payload.sessionId).toBeNull();
    expect(payload.isProcessed).toBe(false);
    expect(payload.processedParts).toBeNull();
    expect(payload.selectedBranches).toBeNull();
    expect("isAutoGenerated" in payload).toBe(false);
  });
});
