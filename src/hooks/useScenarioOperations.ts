import { collection, deleteDoc, doc, getDocs, writeBatch, type WriteBatch } from "firebase/firestore";
import { db } from "../lib/firebase";
import { useDialog } from "../contexts/DialogContext";
import type { ScenarioEvent } from "../types/scenario";
import {
  applyAbsoluteEventTimes,
  batchDeleteEvent,
  batchUpdateEvent,
  commitInChunks,
  deleteEventsInChunks,
  setEventsInChunks,
  resetEventToPending,
} from "../services/eventService";

const deleteRef = (ref: import("firebase/firestore").DocumentReference) => (batch: WriteBatch) => batch.delete(ref);

export function useScenarioOperations() {
  const { alert, confirm } = useDialog();

  const startGameNow = async (events: ScenarioEvent[], startPinEventId = "") => {
    const unstartedEvents = events.filter(ev => !ev.isProcessed && ev.isAutoGenerated !== true);
    if (unstartedEvents.length === 0) {
      await alert({ title: "お知らせ", message: "開戦待ちの未処理イベントがありません。", variant: "info" });
      return false;
    }

    const isOk = await confirm({
      title: "ゲームの開始（開戦）",
      message: "開戦と同時に、古い自動リピートデータを消去してから手動タイムスケジュールを同期起動します。よろしいですか？",
      confirmText: "ゲームを開始する"
    });

    if (!isOk) return false;

    try {
      const batch = writeBatch(db);
      const now = Date.now();

      const autoEvents = events.filter(ev => ev.isAutoGenerated === true);
      autoEvents.forEach(ev => batchDeleteEvent(batch, ev.id));

      applyAbsoluteEventTimes(batch, unstartedEvents, now, startPinEventId);

      batch.update(doc(db, "settings", "system"), { globalPhase: "RUNNING" });
      await batch.commit();
      await alert({ title: "開戦", message: "クリーンアップを完了し、タイムスケジュールを開始しました！", variant: "success" });
      return true;
    } catch (e) {
      console.error(e);
      await alert({ title: "エラー", message: "開戦処理に失敗しました。", variant: "danger" });
      return false;
    }
  };

  const resetAllToPending = async (events: ScenarioEvent[]) => {
    if (events.length === 0) {
      await alert({ title: "お知らせ", message: "リセット対象のイベントがありません。", variant: "info" });
      return false;
    }

    const isOk = await confirm({
      title: "シナリオを最初に戻す",
      message: "現在の市場フェーズは維持したまま、自動ループを停止し、全イベントを開始前の状態に戻し、配信済みニュースと自動生成イベントをすべて削除します。よろしいですか？",
      confirmText: "最初に戻す",
      variant: "warning"
    });

    if (!isOk) return false;

    try {
      const newsSnapshot = await getDocs(collection(db, "news"));
      const scheduledPostNewsSnapshot = await getDocs(collection(db, "scheduled_post_news"));
      const operations: Array<(batch: WriteBatch) => void> = [
        ...newsSnapshot.docs.map(newsDoc => deleteRef(newsDoc.ref)),
        ...scheduledPostNewsSnapshot.docs.map(newsDoc => deleteRef(newsDoc.ref)),
        ...events.map(ev => (batch: WriteBatch) => {
          if (ev.isAutoGenerated === true) {
            batchDeleteEvent(batch, ev.id);
            return;
          }
          batchUpdateEvent(batch, ev.id, {
            isProcessed: false,
            time: null,
            processedParts: null,
            selectedBranches: null
          });
        }),
        (batch: WriteBatch) => batch.update(doc(db, "settings", "system"), { loopEnabled: false })
      ];

      await commitInChunks(operations);
      await alert({
        title: "リセット完了",
        message: "シナリオを開始前に戻し、配信済みニュースと自動生成イベントを削除しました。",
        variant: "success"
      });
      return true;
    } catch (e) {
      console.error(e);
      await alert({ title: "エラー", message: "リセットに失敗しました。", variant: "danger" });
      return false;
    }
  };

  const deleteNewsInChunks = async (newsIds: string[]) => {
    await commitInChunks(newsIds.map(id => (batch: WriteBatch) => batch.delete(doc(db, "news", id))));
  };

  const deleteLiveNews = async (newsId: string, title: string) => {
    const isOk = await confirm({
      title: "配信済みニュースの取り消し",
      message: `『${title}』を非表示にして消去しますか？`,
      variant: "danger",
      confirmText: "ニュースを消去する"
    });

    if (!isOk) return false;

    try {
      await deleteDoc(doc(db, "news", newsId));
      await alert({ title: "消去完了", message: "消去しました。", variant: "success" });
      return true;
    } catch {
      await alert({ title: "エラー", message: "消去に失敗しました。", variant: "danger" });
      return false;
    }
  };

  return { startGameNow, resetAllToPending, deleteLiveNews, deleteEventsInChunks, setEventsInChunks, deleteNewsInChunks, resetEventToPending };
}
